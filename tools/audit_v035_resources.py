"""Inspect actual full-scene textures and cached documented techniques, offline."""
from pathlib import Path
import datetime, hashlib, json, struct, zlib
from PIL import Image

LAB = Path(__file__).resolve().parents[1]
ROOT = LAB / 'experiments/3d-lab/assets/import-v035-full'
E = LAB / 'docs/evidence/v035-main-interface'
scene = json.loads((ROOT/'scene.json').read_text(encoding='utf-8'))
cache = LAB/'tools/tmp/maker-cache-9C6Hcl/tapcode-sce.spark.xd.com/src/engine-res'
manifest_path = cache/'1.32.12/manifest-8418afd4.json'
manifest = json.loads(manifest_path.read_text(encoding='utf-8'))

def all_dicts(value):
    if isinstance(value, dict):
        yield value
        for child in value.values(): yield from all_dicts(child)
    elif isinstance(value, list):
        for child in value: yield from all_dicts(child)

entries = {x['fs_path']: x for x in all_dicts(manifest) if 'fs_path' in x}
textures, materials, techniques = {}, [], {}
used = {m['materialId'] for m in scene['meshFiles']}
normal_ids = set()
for m in scene['materials']:
    if m['id'] not in used: continue
    normal = bool(m.get('normalTexture'))
    name = 'PBRDiffNormal' if normal else ('PBRDiff' if m.get('baseColorTexture') else 'PBRNoTexture')
    directory = 'Techniques/PBR/'
    if m.get('unlit'):
        assert not normal
        directory = 'Techniques/'
        name = 'DiffUnlit' if m.get('baseColorTexture') else 'NoTextureUnlit'
    if m['alphaMode'] == 'BLEND': name += 'Alpha'
    assert m['alphaMode'] in ('BLEND','OPAQUE')
    technique = directory + name + '.xml'
    record = entries[technique]
    cached = cache/'assets'/f"{record['uuid']}-{record['hash']}{record['ext']}"
    xml = cached.read_text(encoding='utf-8-sig')
    assert '<technique' in xml
    if normal:
        assert 'NORMALMAP' in xml and 'DIFFMAP' in xml
        assert m['textureColorSpaces']['normalTexture'] == 'linear'
        assert m['normalMapConvention'] == 'tangent-space OpenGL +Y; requires tangent basis derived from uv0'
        normal_ids.add(m['id'])
    techniques[technique] = {'cachePath':str(cached),'sha256':hashlib.sha256(cached.read_bytes()).hexdigest()}
    materials.append({'id':m['id'],'technique':technique,'normal':normal,'whiteFallback':normal and not m.get('baseColorTexture')})
    for key in ('baseColorTexture','normalTexture'):
        filename=m.get(key)
        if not filename or filename in textures: continue
        path=ROOT/filename
        assert path.resolve().is_relative_to(ROOT.resolve())
        with Image.open(path) as im:
            assert im.format=='PNG'
            im.load()
            textures[filename]={'size':list(im.size),'mode':im.mode,'bytes':path.stat().st_size,
                'rgba8Bytes':im.width*im.height*4,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'decoded':True}

# A utility constant texture, not replacement artwork. The engine's cached
# Default_white.png is KTX-compressed despite its extension, so do not rename it
# or claim its pixels were verified. Emit and inspect a literal RGBA white PNG.
def chunk(kind,payload):
    return struct.pack('>I',len(payload))+kind+payload+struct.pack('>I',zlib.crc32(kind+payload)&0xffffffff)
white = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',1,1,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(b'\0\xff\xff\xff\xff'))+chunk(b'IEND',b'')
target=LAB/'v035/assets/engine-support/default-white.png'
if target.exists(): assert target.read_bytes()==white, 'Unknown utility image; refuse overwrite'
target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(white)
with Image.open(target) as im:
    assert im.size==(1,1) and im.getpixel((0,0))==(255,255,255,255)
normal_triangles=sum(m['triangles'] for m in scene['meshFiles'] if m['materialId'] in normal_ids)
base=sum(m['triangles'] for m in scene['meshFiles'])*3*32
tangent=normal_triangles*3*16
report={'timestampUtc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'status':'PASS',
    'textures':textures,'materials':materials,'techniques':techniques,'normalMaterials':len(normal_ids),
    'whiteFallback':{'path':str(target),'sha256':hashlib.sha256(white).hexdigest(),'rgba':[255,255,255,255],'source':'literal constant generated by this script; no source scene file changed'},
    'normalTriangles':normal_triangles,'expandedPositionNormalUvBytes':base,'additionalTangentBytes':tangent,
    'expandedVertexBytesIncludingTangents':base+tangent,'textureRGBA8BytesNoMips':sum(x['rgba8Bytes'] for x in textures.values()),
    'nativeVerified':False,'limitations':['GPU/CPU copies, index buffers, engine overhead, shadows and Lua peak are excluded','Technique existence and PNG decoding do not prove native tangent API or TBN appearance']}
(E/'full-resource-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({k:v for k,v in report.items() if k not in ('textures','materials','techniques')},ensure_ascii=False,indent=2))
